export type TranslationKey = keyof typeof translations.en;

export function useTranslation() {
  const [language, setLanguage] = useState<Language>('en');

  useEffect(() => {
    const update = () => {
      const next = window.localStorage.getItem('civic-language') === 'hi' ? 'hi' : 'en';
      setLanguage(next);
      document.documentElement.lang = next;
    };
    update();
    window.addEventListener('civic-language-change', update);
    return () => window.removeEventListener('civic-language-change', update);
  }, []);

  return {
    language,
    t: (key: TranslationKey) => translations[language][key],
  };
}
